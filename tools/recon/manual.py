def _shifted(f, dx, dy, head, eyes, bbox, **kw):
    """把参考锚点的 head/eyes/bbox 整体平移 (dx, dy)，bbox 裁到画面内。"""
    x, y, w, h = bbox
    x0, y0 = max(0.0, x + dx), max(0.0, y + dy)
    x1, y1 = min(1280.0, x + dx + w), min(720.0, y + dy + h)
    a = {"frame": f, "head": [round(head[0] + dx, 1), round(head[1] + dy, 1), head[2], head[3]],
         "eyes": [[round(e[0] + dx, 1), round(e[1] + dy, 1)] for e in eyes],
         "bbox": [round(x0, 1), round(y0, 1), round(x1 - x0, 1), round(y1 - y0, 1)], "source": "manual"}
    a.update(kw)
    return a


