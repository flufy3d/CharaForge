def _lerp_box(anchors, f):
    ks = [a for a in anchors if a.get("bbox")]
    if not ks:
        return None
    if f <= ks[0]["frame"]:
        return list(ks[0]["bbox"])
    if f >= ks[-1]["frame"]:
        return list(ks[-1]["bbox"])
    for a, b in zip(ks, ks[1:]):
        if a["frame"] <= f <= b["frame"]:
            t = (f - a["frame"]) / (b["frame"] - a["frame"])
            return [round(x + (y - x) * t, 1) for x, y in zip(a["bbox"], b["bbox"])]


