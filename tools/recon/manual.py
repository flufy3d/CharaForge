def BORDER(s, e):
    """片中常驻的上下“窗帘”装饰边框，叠在角色前面。
    B1：窗帘随节拍上下起伏（内边缘 y≈40~110 / 580~690），固定的 62 / 652 时而盖不全、时而多盖；
    有 curtain.json（curtain.py 逐帧检测）时按每 2 帧一个关键帧写排除区，否则退回固定值。"""
    global _CURTAIN
    if _CURTAIN is None:
        p = os.path.join(os.path.dirname(__file__), "curtain.json")
        _CURTAIN = json.load(open(p, encoding="utf-8"))["frames"] if os.path.exists(p) else []
    if len(_CURTAIN) < e or s not in DYN_BORDER:
        return [EX("frame", s, e, [(s, [0, 0, 1280, 62])]), EX("frame", s, e, [(s, [0, 652, 1280, 68])])]
    fs = list(range(s, e, 2)) + ([e - 1] if (e - 1 - s) % 2 else [])
    top = [(f, [0, 0, 1280, max(1, _CURTAIN[f][0])]) for f in fs]   # 没有窗帘的帧给 1px（schema 要求宽高为正）
    bot = [(f, [0, min(719, _CURTAIN[f][1]), 1280, max(1, 720 - _CURTAIN[f][1])]) for f in fs]
    return [EX("frame", s, e, top), EX("frame", s, e, bot)]


def FX(kind, s, e, note=""):
    d = {"kind": kind, "start": s, "end": e}
    if note:
        d["note"] = note
    return d


def SW(frame, param, value, conf=0.6, note="", fade=None):
    """fade 缺省：表情热键（key*/Clothes*）按 VTS 0.5s 淡入 = 30 帧；Movement* 由 motion 触发，阶跃 = 0。
    实测到明显不同的淡入时长时显式给出。"""
    if fade is None:
        fade = 0 if param.startswith("Movement") else 30
    d = {"frame": frame, "param": param, "value": value, "fade": fade, "confidence": conf}
    if note:
        d["note"] = note
    return d


def MH(motion, start, conf=0.5, note=""):
    d = {"motion": motion, "start": start, "confidence": conf}
    if note:
        d["note"] = note
    return d


def I(id, role, z, anchors, variant=None, sw=None, mh=None, clip=None, flipX=False, grade=None, notes="",
      mode="lk"):
    d = {"id": id, "role": role, "z": z, "variant": variant or {}, "switchEvents": sw or [],
         "motionHints": mh or [], "anchors": anchors, "trackMode": mode, "flipX": flipX}
    if clip is not None:
        d["clip"] = clip
    if grade:
        d["colorGrade"] = grade
    if notes:
        d["notes"] = notes
    return d


