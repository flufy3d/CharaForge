def BODY3(frame, pts, s=None, conf=0.15, **kw):
    """pts: {标志点名: (x, y) 视频像素}。按图集默认姿态做「缩放+平移」（不估旋转）反推两眼中点与眼距，再给 head。
    s 缺省时由标志点间距最小二乘估计；只有一个点时必须给 s。"""
    g = [_GAL[k] for k in pts]; v = list(pts.values())
    gm = (sum(p[0] for p in g) / len(g), sum(p[1] for p in g) / len(g))
    vm = (sum(p[0] for p in v) / len(v), sum(p[1] for p in v) / len(v))
    if s is None:
        num = sum((a[0] - vm[0]) * (b[0] - gm[0]) + (a[1] - vm[1]) * (b[1] - gm[1]) for a, b in zip(v, g))
        den = sum((b[0] - gm[0]) ** 2 + (b[1] - gm[1]) ** 2 for b in g)
        s = num / den
    mid = (vm[0] + s * (_GAL_EYE_MID[0] - gm[0]), vm[1] + s * (_GAL_EYE_MID[1] - gm[1]))
    return VH3(frame, mid, s * _GAL_EYE_D, conf, source="manual-body", **kw)


