# head / bbox 由两眼中点与眼距 d 按体型比例推算（_S15_BOX），只作初值。
def _S15_BOX(kind, eyes):
    (ax, ay), (bx, by) = eyes
    mx, my, d = (ax + bx) / 2, (ay + by) / 2, max(8.0, ((bx - ax) ** 2 + (by - ay) ** 2) ** 0.5)
    k = {"full": ((1.8, 2.0, 3.6, 3.1), (3.0, 2.2, 7.2, 13.2)),
         "chibi": ((1.9, 2.1, 3.8, 2.9), (2.1, 2.2, 4.2, 5.4)),
         "half": ((2.0, 1.9, 4.0, 3.0), (3.6, 2.0, 7.2, 99.0))}[kind]
    def box(c):
        x0, y0 = mx - c[0] * d, my - c[1] * d
        x1, y1 = x0 + c[2] * d, y0 + c[3] * d
        x0, y0, x1, y1 = max(0, x0), max(0, y0), min(1280, x1), min(720, y1)
        return [round(x0, 1), round(y0, 1), round(x1 - x0, 1), round(y1 - y0, 1)]
    return box(k[0]), box(k[1])


def VE(frame, kind, eyes, **kw):
    """s15 用：给两眼（视频像素），head/bbox 按体型推算。kw 可覆盖 head/bbox，或加 opacity/blurSigma/confidence。"""
    head, bbox = _S15_BOX(kind, eyes)
    a = {"frame": frame, "head": kw.pop("head", head), "bbox": kw.pop("bbox", bbox), "eyes": [list(e) for e in eyes]}
    a.update(kw)
    return a


def _flipV(frame, sx, axis=955.0, ref_eyes=((953, 184), (983, 181))):
    """翻牌期间：bbox/head 以竖直轴 axis 为中心按 scaleX 压扁；不给 eyes（压扁后不可读）。"""
    head, bbox = _S15_BOX("full", ref_eyes)
    sq = lambda r: [round(axis + (r[0] - axis) * sx, 1), r[1], round(max(2.0, r[2] * sx), 1), r[3]]
    return {"frame": frame, "head": sq(head), "bbox": sq(bbox), "eyesState": "hidden", "confidence": 0.4}


