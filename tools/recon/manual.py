import math as _m


def _head_from(mid, d):
    """与拟合器约定一致的 head 框：两眼在框高 55%、水平 32%/68% 处（tools/fit plans.ts 用 head 估眼睛时的反算）。"""
    w, h = 2.78 * d, 3.0 * d
    return [round(mid[0] - 0.5 * w, 1), round(mid[1] - 0.55 * h, 1), round(w, 1), round(h, 1)]


def VE3(frame, eyes, conf, state="open", **kw):
    """眼睛可见的锚点：head 由两眼推出，rotation 取两眼连线角度。"""
    (lx, ly), (rx, ry) = eyes
    mid, d = ((lx + rx) / 2, (ly + ry) / 2), _m.hypot(rx - lx, ry - ly)
    a = {"frame": frame, "eyes": [[lx, ly], [rx, ry]], "eyesState": state, "source": "manual", "confidence": conf,
         "rotation": round(_m.degrees(_m.atan2(ry - ly, rx - lx)), 1)}
    if "head" not in kw:
        a["head"] = _head_from(mid, d)
    a.update(kw)
    return a


def VH3(frame, mid, d, conf, **kw):
    """眼睛看不到（出画/被遮挡）的锚点：只给 head 的估计，eyesState=hidden。"""
    a = {"frame": frame, "head": _head_from(mid, d), "eyesState": "hidden", "source": "manual", "confidence": conf}
    a.update(kw)
    return a


